/*
 * The handful of icons the chrome uses, drawn here so the library needs no icon package. Each is a 24 by 24 outline
 * in the color of the text around it; its size comes from a class, the way the chrome already sizes them.
 */

export interface IconProps {
  className?: string;
  /** "currentColor" for the few that are filled in (play, pause, stop). Left out, the icon is an outline. */
  fill?: string;
}

function Icon({ className, fill = "none", children }: IconProps & { children: ReactNode }) {
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      width="24"
      height="24"
      viewBox="0 0 24 24"
      fill={fill}
      stroke="currentColor"
      strokeWidth="2"
      strokeLinecap="round"
      strokeLinejoin="round"
      className={className}
      aria-hidden="true"
    >
      {children}
    </svg>
  );
}

